-- ---------------------------------------------------------
-- STORAGE - bucket para PDFs
-- ---------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('lead-files', 'lead-files', false, 10485760, array['application/pdf'])
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

do $$
begin
    if not exists (
        select 1 from pg_policies
        where schemaname = 'storage'
          and tablename = 'objects'
          and policyname = 'lead_files_select'
    ) then
        create policy lead_files_select
            on storage.objects
            for select
            to authenticated
            using (bucket_id = 'lead-files');
    end if;

    if not exists (
        select 1 from pg_policies
        where schemaname = 'storage'
          and tablename = 'objects'
          and policyname = 'lead_files_insert'
    ) then
        create policy lead_files_insert
            on storage.objects
            for insert
            to authenticated
            with check (bucket_id = 'lead-files');
    end if;

    if not exists (
        select 1 from pg_policies
        where schemaname = 'storage'
          and tablename = 'objects'
          and policyname = 'lead_files_update'
    ) then
        create policy lead_files_update
            on storage.objects
            for update
            to authenticated
            using (bucket_id = 'lead-files')
            with check (bucket_id = 'lead-files');
    end if;

    if not exists (
        select 1 from pg_policies
        where schemaname = 'storage'
          and tablename = 'objects'
          and policyname = 'lead_files_delete'
    ) then
        create policy lead_files_delete
            on storage.objects
            for delete
            to authenticated
            using (bucket_id = 'lead-files');
    end if;
end
$$;

