alter table public.pipeline_stages add column if not exists ordem integer default 0;

do $$
begin
    if exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'pipeline_stages'
          and column_name = 'title'
    ) then
        execute '
            update public.pipeline_stages
            set nome = coalesce(nullif(nome, ''''), title)
            where nome is null or nome = ''''
        ';
    end if;

    if exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'pipeline_stages'
          and column_name = 'name'
    ) then
        execute '
            update public.pipeline_stages
            set nome = coalesce(nullif(nome, ''''), name)
            where nome is null or nome = ''''
        ';
    end if;
end
$$;

