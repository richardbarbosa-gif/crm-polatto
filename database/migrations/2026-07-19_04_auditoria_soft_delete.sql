alter table if exists public.documentos_lead add column if not exists deleted_at timestamptz;

create or replace function public.restaurar_registro(p_tabela text, p_id text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
    v_permitidas text[] := array['negocios', 'pessoas', 'organizacoes', 'tarefas', 'funcionarios', 'documentos_lead'];
begin
    if not (p_tabela = any(v_permitidas)) then
        raise exception 'Tabela % não suporta restauração.', p_tabela;
    end if;

    execute format(
        'update public.%I set deleted_at = null where id::text = $1 and public.tenant_filter(tenant_id)',
        p_tabela
    ) using p_id;

    return found;
end;
$$;

comment on function public.restaurar_registro(text, text) is 'Desfaz soft delete de um registro do próprio tenant. Ex.: select restaurar_registro(''negocios'', ''<uuid>'');';
