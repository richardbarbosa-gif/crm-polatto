-- ---------------------------------------------------------------------
-- CLIENTES — modelo legado. A migration 01 transforma isto na view de
-- compatibilidade sobre negocios; aqui ele nasce como tabela para que a
-- sequência de virada funcione igual em banco novo e em produção.
-- ---------------------------------------------------------------------
create table if not exists public.clientes (
    id bigint generated by default as identity primary key,
    tenant_id uuid,
    nome text,
    cpf_cnpj text,
    telefone text,
    email text,
    ddi text default '+55',
    cep text,
    endereco_instalacao text,
    numero text,
    complemento text,
    conta_energia_media numeric,
    valor numeric,
    status text,
    stage_id bigint,
    temperatura text,
    responsavel text,
    responsavel_id uuid,
    motivo_perda text,
    data_fechamento timestamptz,
    created_at timestamptz default now()
);

do $$
declare
    v_coluna text;
begin
    -- Só faz sentido enquanto clientes for TABELA (depois da virada é view)
    if exists (
        select 1 from information_schema.tables
        where table_schema = 'public' and table_name = 'clientes' and table_type = 'BASE TABLE'
    ) then
        foreach v_coluna in array array[
            'tenant_id uuid', 'nome text', 'cpf_cnpj text', 'telefone text', 'email text',
            'ddi text', 'cep text', 'endereco_instalacao text', 'numero text',
            'complemento text', 'conta_energia_media numeric', 'valor numeric',
            'status text', 'temperatura text', 'responsavel text', 'responsavel_id uuid',
            'motivo_perda text', 'data_fechamento timestamptz', 'created_at timestamptz'
        ] loop
            execute format('alter table public.clientes add column if not exists %s', v_coluna);
        end loop;
    end if;
end $$;

