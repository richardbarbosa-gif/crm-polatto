-- =====================================================================
-- CRM POLATTO — MIGRATION 00: TABELAS BASE
--
-- PRIMEIRA a rodar. Cria o esqueleto que todas as demais migrations
-- assumem existir: empresas, vínculo de usuários, clientes (modelo
-- legado), funil, equipe, agenda, timeline, documentos e metas.
--
-- Por que existe: as migrations 01..09 partiam do princípio de que essas
-- tabelas já estavam no banco (o que é verdade na instalação atual, criada
-- à mão). Em um projeto Supabase NOVO — cliente novo, ambiente de staging,
-- recuperação de backup — nada disso existia e a sequência não subia.
--
-- IDEMPOTENTE: em bancos que já têm as tabelas, apenas garante colunas
-- faltantes e não toca em dado algum.
-- =====================================================================

