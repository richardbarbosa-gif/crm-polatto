-- ---------------------------------------------------------------------
-- GRANTS — sem isto o PostgREST responde "permission denied" mesmo com a
-- RLS correta. A segurança continua sendo a RLS, não o grant.
-- ---------------------------------------------------------------------
do $$
declare
    v_tabela text;
begin
    foreach v_tabela in array array[
        'empresas', 'utilizadores_empresas', 'clientes', 'pipeline_stages',
        'funcionarios', 'tarefas', 'atividades_lead', 'documentos_lead',
        'cliente_status_history', 'metas'
    ] loop
        if to_regclass('public.' || v_tabela) is not null then
            execute format(
                'grant select, insert, update, delete on public.%I to authenticated',
                v_tabela
            );
        end if;
    end loop;
    execute 'grant usage on all sequences in schema public to authenticated';
exception when insufficient_privilege then
    raise notice 'Sem permissão para GRANT — conferir acesso do role authenticated.';
end $$;

