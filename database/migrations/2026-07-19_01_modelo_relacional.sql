-- ---------------------------------------------------------------------
-- Conversor numérico seguro: aceita numeric, "1234.56", "1.234,56",
-- "R$ 1.234,56" — retorna null em vez de abortar quando não parseável.
-- Usado na migração de dados e na view de compatibilidade.
-- ---------------------------------------------------------------------
create or replace function public.to_numeric_seguro(p_valor text)
returns numeric
language plpgsql
immutable
as $$
declare
    v text;
begin
    if p_valor is null or trim(p_valor) = '' then
        return null;
    end if;
    v := regexp_replace(p_valor, '[^0-9,.\-]', '', 'g');
    if v = '' then
        return null;
    end if;
    -- Formato brasileiro: última vírgula é decimal ("1.234,56" → "1234.56")
    if position(',' in v) > 0 then
        v := replace(replace(v, '.', ''), ',', '.');
    end if;
    return v::numeric;
exception when others then
    return null;
end;
$$;

